import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..", "..", "..");
const routesDir = path.join(root, "artifacts", "api-server", "src", "routes");
const output = path.join(root, "lib", "api-spec", "openapi-runtime.yaml");
const files = (await readdir(routesDir)).filter((name) => name.endsWith(".ts"));
const paths = new Map();

for (const file of files) {
  const source = await readFile(path.join(routesDir, file), "utf8");
  for (const match of source.matchAll(/router\.(get|post|put|patch|delete)\(\s*["']([^"']+)["']/g)) {
    const method = match[1];
    const route = match[2].replace(/:([A-Za-z0-9_]+)/g, "{$1}");
    const methods = paths.get(route) ?? new Set();
    methods.add(method);
    paths.set(route, methods);
  }
}

const yaml = [
  "# Generated by scripts/generate-route-inventory.mjs. Do not edit manually.",
  "openapi: 3.1.0",
  "info:",
  "  title: TodoPay Runtime Route Inventory",
  "  version: 1.0.0",
  "  description: Complete runtime endpoint inventory. Typed public contracts remain in openapi.yaml.",
  "paths:",
];
for (const [route, methods] of [...paths].sort(([a], [b]) => a.localeCompare(b))) {
  yaml.push(`  ${route}:`);
  for (const method of [...methods].sort()) {
    const operationId = `${method}_${route}`.replace(/[{}]/g, "").replace(/[^A-Za-z0-9]+(.)/g, (_, c) => c.toUpperCase());
    yaml.push(`    ${method}:`);
    yaml.push(`      operationId: ${operationId}`);
    yaml.push(`      tags: [${route.split("/")[1] || "root"}]`);
    yaml.push("      responses:");
    yaml.push("        '200':");
    yaml.push("          description: Successful response (see route implementation for the typed payload)");
    yaml.push("        '4XX':");
    yaml.push("          description: Authentication, authorization, or validation error");
  }
}
await writeFile(output, `${yaml.join("\n")}\n`, "utf8");
console.log(`Wrote ${paths.size} routes to ${output}`);
